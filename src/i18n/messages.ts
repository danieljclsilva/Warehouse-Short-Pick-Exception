const dictionaries = { en, nl, pl, es } satisfies Record<Locale, typeof en>;

export type MessageKey = keyof typeof en;

export function getMessages(locale: string | null | undefined) {
  const normalized = supportedLocales.includes(locale as Locale) ? (locale as Locale) : "en";
  return { locale: normalized, messages: dictionaries[normalized] };
}

export function translate(
  messages: (typeof en),
  key: MessageKey,
  values?: Record<string, string>,
) {
  const template: string = messages[key];
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => values[name] ?? "");
}
